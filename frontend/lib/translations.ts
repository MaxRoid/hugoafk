export function getTranslation(lang: 'de' | 'en', key: string): string {
  const dict = translations[lang] || translations.de;
  if (dict && dict[key] !== undefined) {
    return dict[key];
  }
  const fallback = translations.en;
  if (fallback && fallback[key] !== undefined) {
    return fallback[key];
  }
  return key;
}
